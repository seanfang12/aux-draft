const mainGenrePools = [
  hipHopSongs,
  throwbackSongs,
  popSongs,
  countrySongs,
  rockSongs,
  rAndBSongs,
  edmSongs
];

function songPoolKey(song) {
  const title = song.title.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/[^a-z0-9]/g, "");
  const artist = song.artist.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/[^a-z0-9]/g, "");
  return `${title}|${artist}`;
}

const allGenreCategoryPools = [];
const allGenreSongs = [];
const assignedAllGenreKeys = [];

// All Genres draws from every room; script.js interleaves these pools so its
// random draft selection stays balanced across styles.
mainGenrePools.forEach((pool) => {
  const categoryPool = [];

  pool.forEach((song) => {
    const key = songPoolKey(song);
    if (!assignedAllGenreKeys.includes(key)) {
      assignedAllGenreKeys.push(key);
      categoryPool.push(song);
      allGenreSongs.push(song);
    }
  });

  allGenreCategoryPools.push(categoryPool);
});

